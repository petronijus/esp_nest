{
    if (level < 0) level = 0;
    if (level > 3) level = 3;
    s_pending_fan = level;
}

void ui_process_pending(void)
{
    int br = s_pending_brightness;
    if (br >= 0) {
        s_pending_brightness = -1;
        if (br != s_brightness) {
            s_brightness = br;
            if (s_brightness > 0) s_last_nonzero_brightness = s_brightness;
            if (s_mode == UI_MODE_BRIGHTNESS) update_brightness_display();
        }
    }

    int fan = s_pending_fan;
    if (fan >= 0) {
        s_pending_fan = -1;
        if (fan != s_fan_level) {
            s_fan_level = fan;
            if (s_fan_level > 0) s_last_nonzero_fan = s_fan_level;
            if (s_mode == UI_MODE_FAN) update_fan_display();
        }
    }

    if (s_status_dirty) {
        s_status_dirty = false;
        if (s_status_label)
            lv_label_set_text(s_status_label, s_pending_status);
    }

    if (s_mode != UI_MODE_MENU && !s_animating) {
        uint32_t elapsed = lv_tick_elaps(s_detail_last_activity);
        if (elapsed >= DETAIL_IDLE_TIMEOUT_MS) {
            ESP_LOGI(TAG, "Detail screen idle timeout, returning to menu");
            if (s_mode == UI_MODE_BRIGHTNESS)
                exit_brightness_mode();
            else if (s_mode == UI_MODE_FAN)
                exit_fan_mode();
            else if (s_mode == UI_MODE_SOUND)
                exit_sound_mode();
            else if (s_mode == UI_MODE_BLINDS)
                exit_blinds_mode();
        }
    }
}

