    lv_anim_t a_lbl;
    lv_anim_init(&a_lbl);
    lv_anim_set_var(&a_lbl, s_fan_label);
    lv_anim_set_values(&a_lbl, LV_OPA_TRANSP, LV_OPA_COVER);
